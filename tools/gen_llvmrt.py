#!/usr/bin/env python3
"""Generates src/llvmrt.p8 from runtime/llvm64_file.ll and runtime/llvm32_file.ll.

The LLVM backend appends this helper text to a module that uses the file
or directory syscalls.  The text is cut into string literals of under 250
bytes at line ends; the declarations are listed apart so the backend can
register each one once, next to its own.

Usage: python3 tools/gen_llvmrt.py runtime/llvm64_file.ll runtime/llvm32_file.ll runtime/llvm16_c64_file.ll > src/llvmrt.p8
"""
import re
import sys


def literal(text):
    out = []
    for ch in text:
        if ch == '\\':
            out.append('\\\\')
        elif ch == '"':
            out.append('\\"')
        elif ch == '\n':
            out.append('\\n')
        elif ch == '\t':
            out.append('\\t')
        else:
            out.append(ch)
    return '"' + ''.join(out) + '"'


def section(path, prefix, declares_name):
    lines = [l.rstrip('\n') for l in open(path, encoding='ascii')]
    declares = []
    body = []
    for line in lines:
        if line.startswith(';'):
            continue
        if line.startswith('declare '):
            name = re.search(r'@([A-Za-z0-9_.]+)\(', line).group(1)
            declares.append((name, line))
        else:
            body.append(line)
    # drop repeated blank lines
    text = re.sub(r'\n{3,}', '\n\n', '\n'.join(body).strip('\n') + '\n')
    chunks = []
    current = ''
    for line in text.split('\n')[:-1]:
        piece = line + '\n'
        if len(piece) > 240:
            raise SystemExit('line too long for a string literal: ' + line[:60])
        if len(current) + len(piece) > 240:
            chunks.append(current)
            current = ''
        current += piece
    if current:
        chunks.append(current)
    upper = prefix.upper()
    print('    const ubyte %s_DECLARES = %d' % (upper, len(declares)))
    print('    str[] %s_declare_names = [' % prefix)
    print(',\n'.join('        ' + literal(n) for n, _ in declares))
    print('    ]')
    print('    str[] %s_declares = [' % prefix)
    print(',\n'.join('        ' + literal(t) for _, t in declares))
    print('    ]')
    print('    const ubyte %s_CHUNKS = %d' % (upper, len(chunks)))
    print('    str[] %s_text = [' % prefix)
    print(',\n'.join('        ' + literal(c) for c in chunks))
    print('    ]')


def main():
    print('; Generated by tools/gen_llvmrt.py from the runtime/*_file.ll files: do not edit.')
    print('; The file and directory helper functions of the llvm targets as LLVM IR text:')
    print('; file_* for llvm64, file32_* for llvm32 (WebAssembly, where size_t and long are 32 bits),')
    print('; file16_* for llvm16 with the mos-c64 profile (the stream routines only: that C library has no fseek).')
    print()
    print('llvmrt {')
    print('    %option ignore_unused')
    print()
    section(sys.argv[1], 'file', 'file')
    print()
    section(sys.argv[2], 'file32', 'file32')
    print()
    section(sys.argv[3], 'file16', 'file16')
    print('}')


if __name__ == '__main__':
    main()
